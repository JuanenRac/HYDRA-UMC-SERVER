import assert from "node:assert/strict";
import { test } from "node:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { completeFromRegistry, loadPortsRegistry, parsePortsRegistry, registryCandidates } from "../src/portsRegistry.ts";

const SAMPLE = `# Generated by tools/sync_ports.py
services:
  - name: HYDRA-UMC-DATALAKE
    port: 8095
    health_path: /stats
    systemd_unit: hydra-umc-datalake.service
  - name: HYDRA-UMC-ORCHESTRATOR
    port: 8114
    health_path: null
    systemd_unit: hydra-umc-orchestrator.service
  - name: HYDRA-UMC-MQTT-BROKER
    port: 1883
    health_path: null
    systemd_unit: null
  - name: HYDRA-UMC-ODD
    port: 99999
    health_path: nothing
    systemd_unit: x.service
`;

test("the generated registry is read: port, health path and unit, with null and bad values dropped", () => {
  const registry = parsePortsRegistry(SAMPLE);
  assert.equal(registry.size, 4);
  assert.deepEqual(registry.get("HYDRA-UMC-DATALAKE"), { name: "HYDRA-UMC-DATALAKE", port: 8095, healthPath: "/stats", systemdUnit: "hydra-umc-datalake.service" });
  assert.deepEqual(registry.get("HYDRA-UMC-ORCHESTRATOR"), { name: "HYDRA-UMC-ORCHESTRATOR", port: 8114, healthPath: null, systemdUnit: "hydra-umc-orchestrator.service" });
  assert.equal(registry.get("HYDRA-UMC-MQTT-BROKER")?.systemdUnit, null);
  assert.equal(registry.get("HYDRA-UMC-ODD")?.port, null);
  assert.equal(registry.get("HYDRA-UMC-ODD")?.healthPath, null);
  assert.equal(parsePortsRegistry("").size, 0);
});

test("what the manifest declares wins; the registry only fills what is missing", () => {
  const registry = parsePortsRegistry(SAMPLE);
  const none = { servicePort: null, serviceHealthPath: null, systemdUnit: null };
  assert.deepEqual(completeFromRegistry("HYDRA-UMC-DATALAKE", none, registry), { servicePort: 8095, serviceHealthPath: "/stats", systemdUnit: "hydra-umc-datalake.service" });
  assert.deepEqual(completeFromRegistry("HYDRA-UMC-DATALAKE", { servicePort: 9000, serviceHealthPath: null, systemdUnit: "mine.service" }, registry), { servicePort: 9000, serviceHealthPath: null, systemdUnit: "mine.service" });
  assert.deepEqual(completeFromRegistry("HYDRA-UMC-UNKNOWN", none, registry), none);
});

test("the registry can be turned off, named, or found next to the other repositories", () => {
  assert.deepEqual(registryCandidates("/eco", { HYDRA_UMC_PORTS_REGISTRY: "off" }), []);
  assert.deepEqual(registryCandidates("/eco", { HYDRA_UMC_PORTS_REGISTRY: path.resolve("x.yaml") }), [path.resolve("x.yaml")]);
  assert.ok(registryCandidates("/eco", {}).some((p) => p.split(path.sep).join("/").endsWith("HYDRA-UMC-SDK/contracts/ports.yaml")));
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "hydra-ports-"));
  assert.equal(loadPortsRegistry(root, {}).size, 0);
  fs.mkdirSync(path.join(root, "HYDRA-UMC-SDK", "contracts"), { recursive: true });
  fs.writeFileSync(path.join(root, "HYDRA-UMC-SDK", "contracts", "ports.yaml"), SAMPLE);
  assert.equal(loadPortsRegistry(root, {}).size, 4);
  assert.equal(loadPortsRegistry(root, { HYDRA_UMC_PORTS_REGISTRY: "off" }).size, 0);
});

test("the real registry of the SDK, when it is next to this repository, reads as 20 or more services with sane ports", () => {
  const real = path.resolve(process.cwd(), "..", "HYDRA-UMC-SDK", "contracts", "ports.yaml");
  if (!fs.existsSync(real)) return;
  const registry = parsePortsRegistry(fs.readFileSync(real, "utf-8"));
  assert.ok(registry.size >= 20, String(registry.size));
  const ports = [...registry.values()].map((s) => s.port).filter((p): p is number => p !== null);
  assert.equal(new Set(ports).size, ports.length, "a port is used twice");
});
