/** The language of the interface: the saved choice, else the language of the browser, else English. */
export function detectLanguage(saved: string | null | undefined, browser: string | null | undefined): Language {
  for (const candidate of [saved, browser]) {
    const code = (candidate ?? '').toLowerCase().slice(0, 2);
    if ((LANGUAGES as readonly string[]).includes(code)) return code as Language;
  }
  return 'en';
}

export function translate(language: Language, key: string): string {
  return MESSAGES[language][key] ?? MESSAGES.en[key] ?? key;
}
